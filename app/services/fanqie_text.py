def decode_text(text: str) -> str:
    if not text:
        return ""
    result = []
    for char in text:
        code = ord(char)
        idx = code - _START_CODE
        if 0 <= idx < len(_CHAR_SEQUENCE):
            result.append(_CHAR_SEQUENCE[idx])
        else:
            result.append(char)
    return "".join(result)
